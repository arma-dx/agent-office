// NOTE: When a rule is redeclared with options, the options of the earlier block (or preset) are
// not merged but replaced entirely. That is why no-restricted-syntax and
// restrict-template-expressions are written out in full below; shared selectors live in one array
// that is spread into every block.

// U+2014 is written as an escape sequence, so this file does not trip its own rule.
const EM_DASH_MESSAGE = 'Do not use the em dash (U+2014); use a hyphen, a comma or a colon.';
const JS_EXTENSION_MESSAGE =
  'Write relative imports with the .ts extension; Node does not resolve .js to a .ts file.';
const RELATIVE_JS = '[source.value=/^\\.{1,2}\\/.*\\.js$/]';

const sharedRestrictedSyntax = [
  { selector: 'Literal[value=/\\u2014/]', message: EM_DASH_MESSAGE },
  { selector: 'TemplateElement[value.cooked=/\\u2014/]', message: EM_DASH_MESSAGE },
  { selector: 'JSXText[value=/\\u2014/]', message: EM_DASH_MESSAGE },
  { selector: `ImportDeclaration${RELATIVE_JS}`, message: JS_EXTENSION_MESSAGE },
  { selector: `ExportNamedDeclaration${RELATIVE_JS}`, message: JS_EXTENSION_MESSAGE },
  { selector: `ExportAllDeclaration${RELATIVE_JS}`, message: JS_EXTENSION_MESSAGE },
  { selector: `ImportExpression${RELATIVE_JS}`, message: JS_EXTENSION_MESSAGE },
];

// Rule 1: code shipped to the browser (apps/web and packages/shared) cannot reach a server-only
// module. Every route is closed: by package name, by relative path and by dynamic import.
const SERVER_ONLY_MESSAGE =
  'Browser code cannot import a server-only module (CLAUDE.md rule 1). Fetch the data through the API.';
const SERVER_ONLY_PACKAGES = [
  '@supabase/*',
  '@anthropic-ai/*',
  '@agent-office/db',
  '@agent-office/db/*',
  'pg',
  'pg/*',
  'pg-boss',
  'pg-boss/*',
  'postgres',
  'postgres/*',
  'node:*',
];
// Reaching the api, worker or db source, or the env schema, through a relative path.
const SERVER_ONLY_RELATIVE = '(^|/)(apps/)?(api|worker)/src/|(^|/)packages/(db/|shared/src/env)';
const SERVER_ONLY_SPECIFIER =
  '^(@supabase\\/|@anthropic-ai\\/|@agent-office\\/(db|shared\\/env)(\\/|$)|pg(-boss)?(\\/|$)|postgres(\\/|$)|node:)';

/**
 * @param {boolean} webBlock
 * @returns {import('eslint').Linter.RulesRecord}
 */
function serverOnlyRules(webBlock) {
  return {
    'no-restricted-syntax': [
      'error',
      ...sharedRestrictedSyntax,
      {
        selector: `ImportExpression[source.value=/${SERVER_ONLY_SPECIFIER}/]`,
        message: SERVER_ONLY_MESSAGE,
      },
      {
        selector: `ImportExpression[source.value=/${SERVER_ONLY_RELATIVE.replaceAll('/', '\\/')}/]`,
        message: SERVER_ONLY_MESSAGE,
      },
      {
        selector: "ImportExpression[source.type!='Literal']",
        message:
          'Write dynamic imports with a constant string; otherwise rule 1 cannot be checked.',
      },
    ],
    'no-restricted-imports': [
      'error',
      {
        patterns: [
          {
            group: webBlock
              ? [...SERVER_ONLY_PACKAGES, '@agent-office/shared/env']
              : SERVER_ONLY_PACKAGES,
            message: SERVER_ONLY_MESSAGE,
          },
          { regex: SERVER_ONLY_RELATIVE, message: SERVER_ONLY_MESSAGE },
        ],
      },
    ],
  };
}

